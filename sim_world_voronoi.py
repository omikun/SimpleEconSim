"""
sim_world_voronoi.py — Architecture B: Native Voronoi Cell Geopolitics for REGNUM.

Transforms irregular Voronoi polygons generated by Mapgen2 into the game's
economic, geopolitical, and demographic regions:
- Each land/coastal Voronoi Center becomes a discrete Region.
- True graph-based adjacency: neighbors derived from shared Voronoi edges (no rigid 6-way hex grid).
- Topography-conforming geopolitics: rivers, sheer cliffs, and mountain ridges naturally
  bound provinces and trade corridors.
- 100% conserved currency, banking, government, and trade compatibility.
"""

